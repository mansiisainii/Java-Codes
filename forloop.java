public class forloop {
    public static void main(String[] args) {
        System.out.println("Welcome to java class");
        for(int i =0;i<10;i++){
            for(int j=0;j<i;j++){
                System.out.print(" * ");
            }
           System.out.println();
        }
        for(int m=5;m>0;m--){
            for(int n=0;n<m;n++){
                System.out.print(" * ");
            }
            System.out.println();
        }
    
    for(int m=5;m>0;m--){
        for(int n=0;n<m;n++){
            System.out.print(" * ");
        }
        System.out.println();
    }
    for(int i =0;i<10;i++){
        for(int j=0;j<i;j++){
            System.out.print(" * ");
        }
        System.out.println();
    }
    
}
    
    
}
